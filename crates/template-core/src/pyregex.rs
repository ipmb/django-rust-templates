//! Python's `\w`, which is not Rust's.
//!
//! Django builds `filter_re` on `\w` (`django/template/base.py:705` `\w+` for a filter
//! name, `base.py:714` `var_chars = r"\w\.\+-"` spliced into `[\w\.\+-]`, and
//! `base.py:1160` `kwarg_re`), so the engine's `\w` must be Python's.
//!
//! Python's `\w` for `str` patterns is exactly `str.isalnum() or '_'` — 142,940 code
//! points, measured equal to `re.fullmatch(r"\w", c)` over the whole range. The `regex`
//! crate's `\w` is `[\p{Alphabetic}\p{M}\p{Nd}\p{Pc}\p{Join_Control}]`, 144,667:
//! 2,642 Rust-only and 915 Python-only (all `No`). `\p{L}\p{N}_` is measured byte-for-byte
//! equal to Python's over U+0000..=U+10FFFF — zero disagreement in both directions —
//! while `[\p{Alphabetic}\p{Nd}\p{Nl}\p{No}_]` is not (1,495 too many), which is why it is
//! `\p{L}\p{N}` and not the `Alphabetic` spelling.
//!
//! **Two spellings, because `\w` is used in two syntactic positions** — bare
//! (`(?P<filter_name>\w+)`) and spliced *inside* a class (`var_chars`). The `regex` crate
//! supports nested character classes, so splicing the standalone form compiles and matches
//! the same code points — correct by accident, and no longer Django's pattern. So each
//! constant is named for its position, and the guard asserts on the pattern *source*.
//!
//! **The guard is the only thing that can see these tables move.** `\p{L}`/`\p{N}` come
//! from `regex-syntax`, versioned independently of CPython's `unicodedata`, and a routine
//! `cargo update` moves it unnoticed by the differential corpus — a UCD skew shows only on
//! recently assigned characters, which no corpus contains.

/// Python's `\w` as a **standalone regular-expression atom** — a complete character
/// class, brackets included. Use where Django writes a bare `\w`:
/// `(?P<filter_name>\w+)` (`base.py:705`) and `kwarg_re`'s `(\w+)=` (`base.py:1160`).
///
/// Do **not** splice this inside a `[...]`; use [`PYTHON_WORD_IN_CLASS`] there.
pub const PYTHON_WORD_STANDALONE: &str = r"[\p{L}\p{N}_]";

/// Python's `\w` as the **contents of a character class**, for splicing inside a
/// `[...]` the caller writes. This is the form for `var_chars = r"\w\.\+-"`
/// (`base.py:714`): `format!(r"[{PYTHON_WORD_IN_CLASS}\.\+-]+")`. Used standalone it means
/// "one letter, one number, then underscores" and rejects `upper` — loud, the safe
/// direction to get wrong.
pub const PYTHON_WORD_IN_CLASS: &str = r"\p{L}\p{N}_";

#[cfg(test)]
mod tests {
    use super::*;
    use regex::Regex;

    /// An inclusive code-point range; a named alias to keep `clippy::type_complexity` off.
    type WordRange = (u32, u32);

    /// Python's `\w`, as inclusive ranges, generated by
    /// `scripts/gen_python_word_ranges.py` from CPython 3.14.4 (UCD 16.0.0). A data file
    /// rather than a `const`: 771 lines of `lo hi` hex, 8,033 bytes, versus 1,805,848 for
    /// the 142,940 code points.
    const PYTHON_WORD_RANGES_TEXT: &str = include_str!("pyregex_word_ranges.txt");

    /// The two Django `\w` positions, spliced with our forms, written by
    /// `tests/test_pyregex_parity.py` from the pinned tree's own `filter_raw_string`: a
    /// `cargo test` cannot read `.django`, so the fixture is derived Python-side.
    const SPLICES: &str = include_str!("../../../tests/pyregex_splices.txt");

    /// The table above, parsed.
    fn python_word_ranges() -> Vec<WordRange> {
        PYTHON_WORD_RANGES_TEXT
            .lines()
            .filter(|line| !line.trim().is_empty())
            .map(|line| {
                let mut parts = line.split_whitespace();
                let lo = u32::from_str_radix(parts.next().expect("lo"), 16).expect("hex lo");
                let hi = u32::from_str_radix(parts.next().expect("hi"), 16).expect("hex hi");
                assert!(parts.next().is_none(), "trailing field on {line:?}");
                (lo, hi)
            })
            .collect()
    }

    /// The class as the `regex` crate actually compiles `pattern`, walked to canonical
    /// ascending, non-adjacent inclusive ranges.
    ///
    /// The point of the guard: `pattern` is built from the exported constants, so the code
    /// points come from the same `regex-syntax` tables the engine's `filter_re` will
    /// compile against.
    fn compiled_ranges(pattern: &str) -> Vec<WordRange> {
        let re = Regex::new(pattern).unwrap_or_else(|e| panic!("{pattern}: {e}"));
        let mut out: Vec<WordRange> = Vec::new();
        for cp in 0u32..=0x10FFFF {
            if (0xD800..=0xDFFF).contains(&cp) {
                continue;
            }
            let c = char::from_u32(cp).unwrap();
            let mut buf = [0u8; 4];
            if re.is_match(c.encode_utf8(&mut buf)) {
                match out.last_mut() {
                    Some(last) if last.1 + 1 == cp => last.1 = cp,
                    _ => out.push((cp, cp)),
                }
            }
        }
        out
    }

    /// The first difference between two range lists, or how they ended.
    fn first_diff(got: &[WordRange], expected: &[WordRange]) -> String {
        for (index, (g, e)) in got.iter().zip(expected).enumerate() {
            if g != e {
                return format!("index {index}: got {g:?}, expected {e:?}");
            }
        }
        format!(
            "equal over the common prefix; got {} ranges, expected {}",
            got.len(),
            expected.len()
        )
    }

    /// The number of code points two range lists cover.
    fn total_codepoints(ranges: &[WordRange]) -> u64 {
        ranges.iter().map(|(lo, hi)| u64::from(hi - lo + 1)).sum()
    }

    /// Whether every code point of `inner` is also in `outer`. Both canonical: ascending,
    /// disjoint, non-adjacent.
    ///
    /// A cursor walk rather than two sets — 1.1M `u32`s per side is a lot of allocation to
    /// answer a question the ranges already answer.
    fn ranges_subset(inner: &[WordRange], outer: &[WordRange]) -> bool {
        let mut cursor = 0usize;
        for &(lo, hi) in inner {
            while cursor < outer.len() && outer[cursor].1 < lo {
                cursor += 1;
            }
            match outer.get(cursor) {
                Some(&(olo, ohi)) if olo <= lo && hi <= ohi => {}
                _ => return false,
            }
        }
        true
    }

    #[test]
    fn the_embedded_table_is_pythons_measured_word_set() {
        let ranges = python_word_ranges();
        assert_eq!(ranges.len(), 771, "range count");
        let total: u64 = ranges.iter().map(|(lo, hi)| u64::from(hi - lo + 1)).sum();
        assert_eq!(total, 142_940, "code points");
        for pair in ranges.windows(2) {
            assert!(pair[0].1 + 1 < pair[1].0, "not canonical at {pair:?}");
        }
    }

    #[test]
    fn the_compiled_class_is_exactly_pythons_word_set() {
        // The one guard that can see `regex-syntax`'s UCD move under us. Both spellings
        // are walked, each wrapped into a complete one-code-point pattern, so neither can
        // drift from the table unnoticed.
        let expected = python_word_ranges();
        for (label, pattern) in [
            ("standalone", format!(r"\A{PYTHON_WORD_STANDALONE}\z")),
            ("in-class", format!(r"\A[{PYTHON_WORD_IN_CLASS}]\z")),
        ] {
            let got = compiled_ranges(&pattern);
            // `assert!` and not `assert_eq!`: on failure `assert_eq!` prints both
            // ~771-range vectors, which buries the one useful line.
            assert!(
                got == expected,
                "the regex crate's `{label}` class has diverged from Python's \
                 \\w: {}",
                first_diff(&got, &expected),
            );
        }
    }

    #[test]
    fn the_two_spellings_are_the_same_set_in_different_positions() {
        // Structure, not a behavioural probe: nested classes are a documented
        // `regex-syntax` guarantee (`[[a][b]]` is union, and `&&`/`--` are part of the
        // same syntax), so a probe that splicing the standalone form inside a class
        // matches could never have failed.
        let standalone = PYTHON_WORD_STANDALONE;
        let in_class = PYTHON_WORD_IN_CLASS;

        assert!(
            standalone.starts_with('[') && standalone.ends_with(']'),
            "the standalone form must be a complete atom, brackets included: {standalone:?}"
        );
        assert!(
            !in_class.contains('[') && !in_class.contains(']'),
            "the in-class form must be bare contents, safe to splice inside a \
             caller's `[...]`: {in_class:?}"
        );
        // The set is the same; only the position differs. This catches the edit that
        // changes one constant and forgets the other.
        assert_eq!(
            format!("[{in_class}]"),
            standalone,
            "the two constants must describe the same set; only their position may differ"
        );
    }

    #[test]
    fn the_in_class_form_used_standalone_is_loudly_wrong() {
        // The other misuse, executable: `\p{L}\p{N}_` read as a whole atom is
        // *concatenation*, not a union — exactly one letter, one number, then one or more
        // underscores — which rejects `upper` and every real variable name, the safe
        // direction to get wrong.
        let misused = Regex::new(&format!(r"\A{PYTHON_WORD_IN_CLASS}+\z")).unwrap();
        assert!(
            misused.is_match("a1_"),
            "one letter, one number, then underscores"
        );
        assert!(misused.is_match("a1___"));
        assert!(
            !misused.is_match("upper"),
            "the loud failure: every variable name"
        );
        assert!(!misused.is_match("a_1"));
        assert!(!misused.is_match("ab1_"));

        // The correct spelling of the same position, for contrast.
        let correct = Regex::new(&format!(r"\A[{PYTHON_WORD_IN_CLASS}]+\z")).unwrap();
        for probe in ["upper", "a_1", "ab1_", "a1_"] {
            assert!(correct.is_match(probe), "{probe:?}");
        }
    }

    #[test]
    fn the_alphabetic_spelling_is_rejected_so_it_cannot_be_simplified_into() {
        // A guard against a **code change**, not UCD drift: it fires when someone
        // "simplifies" `[\p{L}\p{N}_]` to `[\p{Alphabetic}\p{Nd}\p{Nl}\p{No}_]` for reading
        // more semantically — plausible, silent otherwise, and over-accepting by over a
        // thousand code points.
        let expected = python_word_ranges();
        let wrong = compiled_ranges(r"\A[\p{Alphabetic}\p{Nd}\p{Nl}\p{No}_]\z");
        assert!(
            wrong != expected,
            "the `Alphabetic` spelling must not be equal to Python's \\w — if it \
             is, this guard has stopped guarding and the constant's doc needs \
             re-measuring"
        );
        // *How* it is wrong matters: it is a strict superset, so the failure mode is
        // over-acceptance (a template Django rejects compiles here), not a different set.
        assert!(
            ranges_subset(&expected, &wrong),
            "the `Alphabetic` spelling should accept everything Python's \\w does"
        );
        // The helper is not vacuously true — the relation is strict, so it must not hold
        // the other way, or a `ranges_subset` returning `true` unconditionally would make
        // the assertion above decorative.
        assert!(
            !ranges_subset(&wrong, &expected),
            "`ranges_subset` returned true both ways, so it cannot tell a \
             superset from an equal set"
        );
        let extra = total_codepoints(&wrong) - total_codepoints(&expected);
        assert!(
            extra > 0,
            "a strict superset, so it has code points of its own"
        );
    }

    #[test]
    fn superscript_two_is_a_word_character() {
        // Django: `Template("{{ ² }}").render(Context({}))` == "". U+00B2 is `No`;
        // Python's `\w` matches it, Rust's does not.
        let ours = Regex::new(&format!(r"\A{PYTHON_WORD_STANDALONE}\z")).unwrap();
        assert!(ours.is_match("\u{00b2}"));
        assert!(
            !Regex::new(r"\A\w\z").unwrap().is_match("\u{00b2}"),
            "Rust's `\\w` does not match, which is why this is the failing-first case"
        );
    }

    #[test]
    fn combining_acute_is_not_a_word_character() {
        // Django: `Engine().from_string("{{ a\u{0301} }}")` raises "Could not parse
        // the remainder". U+0301 is `Mn` — a Rust `\w` character, not a Python one.
        let ours = Regex::new(&format!(r"\A{PYTHON_WORD_STANDALONE}\z")).unwrap();
        assert!(!ours.is_match("\u{0301}"));
        assert!(
            Regex::new(r"\A\w\z").unwrap().is_match("\u{0301}"),
            "Rust's `\\w` matches, which is why this is the failing-first case"
        );
    }

    #[test]
    fn the_class_leaves_djangos_remainder() {
        // The same two characters, read the way `filter_re` reads a variable: a leading
        // run of the class. This is the observable consequence — what is left over is what
        // Django turns into the error.
        let re = Regex::new(&format!(r"\A[{PYTHON_WORD_IN_CLASS}]+")).unwrap();
        let m = re.find("\u{00b2}").expect("U+00B2 must match");
        assert_eq!(m.end(), "\u{00b2}".len());
        // `m.end()` is a byte offset, so slice on bytes; U+0301 is two bytes.
        let source = "a\u{0301}";
        let m = re.find(source).unwrap();
        assert_eq!(&source[m.end()..], "\u{0301}");
    }

    #[test]
    fn both_forms_splice_reproducing_djangos_pattern_sources() {
        let lines: Vec<&str> = SPLICES
            .lines()
            .filter(|line| !line.trim().is_empty())
            .map(str::trim)
            .collect();
        assert_eq!(
            lines.len(),
            2,
            "fixture must hold exactly two atoms:\n{SPLICES}"
        );
        let (label, atom) = lines[0].split_once(' ').expect("labelled fixture line");
        assert_eq!(label, "filter_name");
        assert_eq!(atom, format!("(?P<filter_name>{PYTHON_WORD_STANDALONE}+)"));
        let (label, atom) = lines[1].split_once(' ').expect("labelled fixture line");
        assert_eq!(label, "var_chars");
        assert_eq!(atom, format!(r"[{PYTHON_WORD_IN_CLASS}\.\+-]+"));
    }
}
